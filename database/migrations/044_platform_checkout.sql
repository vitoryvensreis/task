-- SaaS comercial novo: criação controlada e compra de upgrade sem reutilizar SaaS removido.
CREATE TABLE IF NOT EXISTS platform_checkout_orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT NOT NULL,
 workspace_id BIGINT UNSIGNED NOT NULL,
 plan_id BIGINT UNSIGNED NOT NULL,
 extra_seats INT UNSIGNED NOT NULL DEFAULT 0,
 verify_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 token_expires_at DATETIME NOT NULL,
 verified_at DATETIME NULL,
 status VARCHAR(32) NOT NULL DEFAULT 'awaiting_email',
 created_at DATETIME NOT NULL,
 updated_at DATETIME NOT NULL,
 activated_at DATETIME NULL,
 UNIQUE KEY uq_checkout_workspace(workspace_id),
 UNIQUE KEY uq_checkout_user(user_id),
 UNIQUE KEY uq_checkout_verify(verify_hash),
 CONSTRAINT fk_checkout_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_checkout_workspace FOREIGN KEY(workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
 CONSTRAINT fk_checkout_plan FOREIGN KEY(plan_id) REFERENCES platform_access_plans(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS platform_subscription_changes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 workspace_id BIGINT UNSIGNED NOT NULL,
 subscription_id BIGINT UNSIGNED NOT NULL,
 requested_by INT NOT NULL,
 change_type VARCHAR(24) NOT NULL,
 target_plan_id BIGINT UNSIGNED NOT NULL,
 target_extra_seats INT UNSIGNED NOT NULL,
 old_amount_cents BIGINT UNSIGNED NOT NULL,
 target_amount_cents BIGINT UNSIGNED NOT NULL,
 amount_due_cents BIGINT UNSIGNED NOT NULL,
 asaas_payment_id VARCHAR(90) CHARACTER SET ascii COLLATE ascii_bin NULL,
 invoice_url VARCHAR(1024) NULL,
 status VARCHAR(32) NOT NULL DEFAULT 'creating',
 last_error VARCHAR(120) NULL,
 created_at DATETIME NOT NULL,
 updated_at DATETIME NOT NULL,
 paid_at DATETIME NULL,
 applied_at DATETIME NULL,
 UNIQUE KEY uq_change_payment(asaas_payment_id),
 KEY idx_change_workspace_status(workspace_id,status,id),
 KEY idx_change_pending(status,id),
 CONSTRAINT fk_change_workspace FOREIGN KEY(workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
 CONSTRAINT fk_change_sub FOREIGN KEY(subscription_id) REFERENCES platform_asaas_subscriptions(id) ON DELETE RESTRICT,
 CONSTRAINT fk_change_user FOREIGN KEY(requested_by) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_change_plan FOREIGN KEY(target_plan_id) REFERENCES platform_access_plans(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
